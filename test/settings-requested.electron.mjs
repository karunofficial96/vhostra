// Opt-in renderer transaction test with a delayed isolated backend handler.
import assert from 'node:assert/strict'
import { app, ipcMain } from 'electron'
import { mkdtempSync } from 'node:fs'
import { rm, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'

const profile = mkdtempSync(path.join(os.tmpdir(), 'vhostra-settings-requested-'))
app.setPath('userData', profile)
const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
const deadline = setTimeout(() => app.exit(1), 120000)
app.whenReady().then(async () => {
  let window, runtime, passed = false
  try {
    const { VhostraStore } = await import('../dist-electron/store.js')
    const store = new VhostraStore(profile, path.resolve('dist-welcome'))
    await store.saveOnboarding({ ...await store.getOnboarding(), completed: true })
    const initial = await store.getState()
    await store.saveSettings({ ...initial.settings, selectedPhpVersion: '8.1', startup: { ...initial.settings.startup, serviceStartMode: 'manual' } })
    const { applicationSession } = await import('../dist-electron/main.js')
    await pause(500)
    ;({ window, runtime } = applicationSession())
    window.webContents.on('console-message', (_event, level, message) => { if (level >= 2) console.error('Renderer console:', message) })
    runtime.scope = `vhostra-settings-requested-${process.pid}`
    let fail = true
    let operation = 0
    let staleFinalRead = null
    let staleFinalReadServed = false
    ipcMain.removeHandler('vhostra:get-state')
    ipcMain.handle('vhostra:get-state', async () => {
      if (staleFinalRead) { const stale = staleFinalRead; staleFinalRead = null; staleFinalReadServed = true; return stale }
      return store.getState()
    })
    ipcMain.removeHandler('vhostra:save-settings')
    ipcMain.handle('vhostra:save-settings', async (_event, next) => {
      const previous = await store.getState()
      runtime.progress = { id: ++operation, lines: [], total: 0 }
      runtime.set({ state: 'starting', message: 'Preparing candidate runtime', services: [] })
      await pause(450)
      if (fail) throw Error('Injected candidate failure')
      const saved = await store.saveSettings(next)
      if (previous.settings.selectedPhpVersion === '8.1' && next.selectedPhpVersion === '8.3') staleFinalRead = previous
      return saved
    })
    const evaluate = async code => { try { return await window.webContents.executeJavaScript(code) } catch (error) { throw Error(`Renderer assertion failed: ${code}: ${error}`) } }
    const waitFor = async code => { const until = Date.now() + 10000; while (!await evaluate(code)) { if (Date.now() > until) throw Error(`UI timeout: ${code}`); await pause(50) } }
    await waitFor('document.body.textContent.includes("Dashboard")')
    await evaluate(`([...document.querySelectorAll('button')].find(button=>button.textContent==='Settings')).click()`)
    await waitFor('document.body.textContent.includes("Shared environment")')
    assert.equal(await evaluate(`[...document.querySelectorAll('h2')].filter(node=>node.textContent==='Runtime Status').length`), 1)
    await writeFile('/private/tmp/vhostra-top-settings.png', (await window.webContents.capturePage()).toPNG())
    const select = async (label, value) => evaluate(`(()=>{const control=[...document.querySelectorAll('label')].find(item=>item.textContent.includes(${JSON.stringify(label)})).querySelector('select');Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(control,${JSON.stringify(value)});control.dispatchEvent(new Event('change',{bubbles:true}))})()`)
    const selected = label => evaluate(`[...document.querySelectorAll('label')].find(item=>item.textContent.includes(${JSON.stringify(label)})).querySelector('select').value`)
    const check = async (label, value) => evaluate(`(()=>{const control=[...document.querySelectorAll('label')].find(item=>item.textContent.includes(${JSON.stringify(label)})).querySelector('input[type=checkbox]');if(control.checked!==${value})control.click()})()`)
    const checked = label => evaluate(`[...document.querySelectorAll('label')].find(item=>item.textContent.includes(${JSON.stringify(label)})).querySelector('input[type=checkbox]').checked`)
    const detailGap = id => evaluate(`(()=>{const card=document.getElementById(${JSON.stringify(id)});const details=card.querySelector('.runtime-progress');const before=details.previousElementSibling.getBoundingClientRect();return Math.round(details.querySelector('.runtime-action-row').getBoundingClientRect().top-before.bottom)})()`)
    const primary = id => evaluate(`document.querySelector('#${id} [role=status]').textContent`)
    const bottomGap = id => evaluate(`(()=>{const card=document.getElementById(${JSON.stringify(id)});const style=getComputedStyle(card);return Math.round(card.getBoundingClientRect().bottom-card.querySelector('.runtime-progress').getBoundingClientRect().bottom-parseFloat(style.borderBottomWidth))})()`)
    await select('Web server', 'nginx'); await pause(40)
    assert.equal(await selected('Web server'), 'nginx')
    assert.equal(await evaluate(`document.body.textContent.includes('Nginx HTTP')`), true)
    assert.equal(await evaluate(`[...document.querySelectorAll('label')].find(item=>item.textContent.includes('Web server')).querySelector('img').alt`), 'Nginx logo')
    assert.equal(await detailGap('runtime-status'), 32)
    assert.equal(await bottomGap('runtime-status'), 16)
    assert.equal(await primary('runtime-status'), 'Switching web server from OpenLiteSpeed to Nginx…')
    await writeFile('/private/tmp/vhostra-settings-runtime-pending.png', (await window.webContents.capturePage()).toPNG())
    await evaluate(`document.querySelector('#runtime-status .runtime-expand').click()`)
    assert.equal(await evaluate(`document.querySelector('#runtime-status .runtime-expand').getAttribute('aria-expanded')`), 'true')
    await pause(180)
    assert.equal(await selected('Web server'), 'nginx')
    assert.equal(await evaluate(`document.body.textContent.includes('Nginx HTTP')`), true)
    await waitFor(`document.body.textContent.includes('Injected candidate failure')`)
    assert.equal(await selected('Web server'), 'openlitespeed')
    assert.equal(await evaluate(`document.body.textContent.includes('OpenLiteSpeed HTTP')`), true)
    fail = false
    await select('Web server', 'nginx'); await pause(40)
    assert.equal(await selected('Web server'), 'nginx')
    assert.equal(await evaluate(`document.body.textContent.includes('Nginx HTTP')`), true)
    await pause(180)
    assert.equal(await selected('Web server'), 'nginx')
    await waitFor(`window.vhostra.getState().then(state=>state.settings.selectedWebServer==='nginx')`)
    await waitFor(`![...document.querySelectorAll('label')].find(item=>item.textContent.includes('PHP version')).querySelector('select').disabled`)
    assert.equal((await store.getState()).settings.selectedWebServer, 'nginx')
    fail = true
    await select('PHP version', '8.4'); await pause(40)
    assert.equal(await selected('PHP version'), '8.4')
    assert.equal(await primary('runtime-status'), 'Switching PHP from 8.1 to 8.4…')
    await pause(180)
    assert.equal(await selected('PHP version'), '8.4')
    await waitFor(`document.body.textContent.includes('Injected candidate failure')`)
    assert.equal(await selected('PHP version'), '8.1')
    assert.match(await evaluate(`document.getElementById('runtime-status').textContent`), /previous verified setting was restored/)
    await check('Enable shared Redis', true); await pause(40)
    assert.equal(await checked('Enable shared Redis'), true)
    assert.equal(await primary('runtime-status'), 'Enabling Redis…')
    await pause(180)
    assert.equal(await checked('Enable shared Redis'), true)
    await waitFor(`document.body.textContent.includes('Injected candidate failure')`)
    assert.equal(await checked('Enable shared Redis'), false)
    await check('Enable shared Memcached', true); await pause(40)
    assert.equal(await checked('Enable shared Memcached'), true)
    assert.equal(await primary('runtime-status'), 'Enabling Memcached…')
    await pause(180)
    assert.equal(await checked('Enable shared Memcached'), true)
    await waitFor(`document.body.textContent.includes('Injected candidate failure')`)
    assert.equal(await checked('Enable shared Memcached'), false)
    fail = false
    await select('PHP version', '8.3'); await pause(180)
    assert.equal(await primary('runtime-status'), 'Switching PHP from 8.1 to 8.3…')
    assert.equal(await selected('PHP version'), '8.3')
    await evaluate(`([...document.querySelectorAll('button')].find(button=>button.textContent==='Services')).click()`)
    await waitFor(`document.getElementById('services-runtime-status')!==null`)
    await waitFor(`([...document.querySelectorAll('article')].some(node=>node.textContent.includes('Redis')))`)
    assert.match(await evaluate(`document.getElementById('services-runtime-status').textContent`), /PHP 8.3|Preparing candidate runtime/)
    await evaluate(`([...document.querySelectorAll('button')].find(button=>button.textContent==='Settings')).click()`)
    await waitFor(`document.getElementById('runtime-status')!==null`)
    assert.equal(await selected('PHP version'), '8.3')
    await waitFor(`window.vhostra.getState().then(state=>state.settings.selectedPhpVersion==='8.3')`)
    await waitFor(`![...document.querySelectorAll('label')].find(item=>item.textContent.includes('PHP version')).querySelector('select').disabled`)
    assert.equal(await selected('PHP version'), '8.3')
    assert.equal(staleFinalReadServed, true)
    await select('PHP version', '8.1'); await pause(180)
    assert.equal(await selected('PHP version'), '8.1')
    await waitFor(`window.vhostra.getState().then(state=>state.settings.selectedPhpVersion==='8.1')`)
    await waitFor(`![...document.querySelectorAll('label')].find(item=>item.textContent.includes('PHP version')).querySelector('select').disabled`)
    await check('Enable shared Redis', true); await pause(180)
    assert.equal(await checked('Enable shared Redis'), true)
    await waitFor(`window.vhostra.getState().then(state=>state.settings.optionalServices.redis)`)
    await waitFor(`![...document.querySelectorAll('label')].find(item=>item.textContent.includes('Enable shared Redis')).querySelector('input').disabled`)
    await check('Enable shared Redis', false); await pause(180)
    assert.equal(await primary('runtime-status'), 'Disabling Redis…')
    assert.equal(await checked('Enable shared Redis'), false)
    await waitFor(`window.vhostra.getState().then(state=>!state.settings.optionalServices.redis)`)
    await waitFor(`![...document.querySelectorAll('label')].find(item=>item.textContent.includes('Enable shared Redis')).querySelector('input').disabled`)
    await check('Enable shared Memcached', true); await pause(180)
    assert.equal(await checked('Enable shared Memcached'), true)
    await waitFor(`window.vhostra.getState().then(state=>state.settings.optionalServices.memcached)`)
    await waitFor(`![...document.querySelectorAll('label')].find(item=>item.textContent.includes('Enable shared Memcached')).querySelector('input').disabled`)
    await check('Enable shared Memcached', false); await pause(180)
    assert.equal(await primary('runtime-status'), 'Disabling Memcached…')
    assert.equal(await checked('Enable shared Memcached'), false)
    await waitFor(`window.vhostra.getState().then(state=>!state.settings.optionalServices.memcached)`)
    await waitFor(`![...document.querySelectorAll('label')].find(item=>item.textContent.includes('Enable shared Memcached')).querySelector('input').disabled`)
    await pause(400)
    assert.equal(await evaluate(`(()=>{const target=document.getElementById('runtime-status').getBoundingClientRect(), pane=document.querySelector('main > section > div.overflow-auto').getBoundingClientRect();return target.top>=pane.top-1&&target.bottom<=pane.bottom+1})()`), true)
    fail = false
    assert.equal(await evaluate(`document.querySelectorAll('input[name="service-start-mode"]:checked').length`), 1)
    assert.equal(await evaluate(`document.querySelector('input[name="service-start-mode"]:checked').value`), 'on')
    await evaluate(`([...document.querySelectorAll('label')].find(label=>label.textContent.trim()==='After login').querySelector('input')).click()`)
    await waitFor(`window.vhostra.getState().then(state=>state.settings.startup.serviceStartMode==='after-login' && state.settings.startup.launchAtLogin)`)
    assert.equal(await evaluate(`document.querySelectorAll('input[name="service-start-mode"]:checked').length`), 1)
    await evaluate(`([...document.querySelectorAll('label')].find(label=>label.textContent.includes('Launch Vhostra on Login')).querySelector('input')).click()`)
    await waitFor(`window.vhostra.getState().then(state=>state.settings.startup.serviceStartMode==='manual' && !state.settings.startup.launchAtLogin)`)
    let serviceRows = [{ id: 'web', label: 'Nginx', enabled: true, state: 'stopped' }, { id: 'mariadb', label: 'MariaDB', enabled: true, state: 'running' }, { id: 'redis', label: 'Redis', enabled: false, state: 'disabled' }, { id: 'memcached', label: 'Memcached', enabled: false, state: 'disabled' }]
    ipcMain.removeHandler('vhostra:list-managed-services')
    ipcMain.handle('vhostra:list-managed-services', () => serviceRows)
    ipcMain.removeHandler('vhostra:control-managed-service')
    ipcMain.handle('vhostra:control-managed-service', async (_event, id, action) => { await pause(300); serviceRows = serviceRows.map(row => row.id === id ? { ...row, state: action === 'stop' ? 'stopped' : 'running' } : row); return serviceRows })
    ipcMain.removeHandler('vhostra:set-optional-service')
    ipcMain.handle('vhostra:set-optional-service', async (_event, id, enabled) => {
      runtime.progress = { id: ++operation, lines: [], total: 0 }
      runtime.set({ state: 'starting', message: `${enabled ? 'Enabling' : 'Disabling'} ${id}`, services: [] })
      await pause(450)
      if (fail) throw Error('Injected candidate failure')
      const current = await store.getState()
      await store.saveSettings({ ...current.settings, optionalServices: { ...current.settings.optionalServices, [id]: enabled } })
      serviceRows = serviceRows.map(row => row.id === id ? { ...row, enabled, state: enabled ? 'running' : 'disabled' } : row)
    })
    await evaluate(`([...document.querySelectorAll('button')].find(button=>button.textContent==='Services')).click()`)
    await waitFor(`document.getElementById('services-runtime-status')!==null`)
    await waitFor(`([...document.querySelectorAll('article')].some(node=>node.textContent.includes('Redis')))`)
    assert.equal(await evaluate(`[...document.querySelectorAll('h2')].filter(node=>node.textContent==='Runtime Status').length`), 1)
    assert.equal(await detailGap('services-runtime-status'), 32)
    assert.equal(await bottomGap('services-runtime-status'), 16)
    await evaluate(`document.querySelector('#services-runtime-status .runtime-expand').click()`)
    assert.equal(await evaluate(`document.querySelector('#services-runtime-status .runtime-expand').getAttribute('aria-expanded')`), 'true')
    await pause(100)
    await writeFile('/private/tmp/vhostra-services-runtime-expanded.png', (await window.webContents.capturePage()).toPNG())
    await evaluate(`([...document.querySelectorAll('article')].find(node=>node.textContent.includes('Redis')).querySelector('button')).click()`)
    await pause(180)
    assert.match(await evaluate(`[...document.querySelectorAll('article')].find(node=>node.textContent.includes('Redis'))?.textContent ?? document.body.textContent.slice(0,600)`), /Configured: Enabled · Status: Enabling/)
    assert.equal(await evaluate(`document.querySelector('#services-runtime-status > p').textContent`), 'Enabling Redis…')
    await waitFor(`window.vhostra.getState().then(state=>state.settings.optionalServices.redis)`)
    await waitFor(`[...document.querySelectorAll('article')].find(node=>node.textContent.includes('Redis')).textContent.includes('Configured: Enabled · Status: running')`)
    fail = true
    await evaluate(`([...document.querySelectorAll('article')].find(node=>node.textContent.includes('Redis')).querySelector('button')).click()`)
    await pause(180)
    assert.match(await evaluate(`[...document.querySelectorAll('article')].find(node=>node.textContent.includes('Redis')).textContent`), /Configured: Disabled · Status: Disabling/)
    assert.equal(await evaluate(`document.querySelector('#services-runtime-status > p').textContent`), 'Disabling Redis…')
    await waitFor(`document.body.textContent.includes('Injected candidate failure')`)
    assert.match(await evaluate(`[...document.querySelectorAll('article')].find(node=>node.textContent.includes('Redis')).textContent`), /Configured: Enabled/)
    fail = false
    await writeFile('/private/tmp/vhostra-top-services.png', (await window.webContents.capturePage()).toPNG())
    await evaluate(`(()=>{const pane=document.getElementById('services-runtime-status').closest('.overflow-auto');pane.style.height='320px';pane.scrollTop=0;const card=[...document.querySelectorAll('article')].find(node=>node.textContent.includes('MariaDB'));card.querySelector('button').click()})()`)
    await waitFor(`document.getElementById('services-runtime-status').textContent.includes('stopped')`)
    await pause(500)
    assert.equal(await evaluate(`document.getElementById('services-runtime-status').closest('.overflow-auto').scrollTop`), 0)
    assert.equal(await evaluate(`document.body.textContent.includes('Ports & Services')`), false)
    await evaluate(`document.getElementById('services-runtime-status').closest('.overflow-auto').scrollTop=0`)
    runtime.set({ state: 'stopped', message: 'Background fixture status', services: [], serviceRevision: 123 })
    await pause(400)
    assert.equal(await evaluate(`document.getElementById('services-runtime-status').closest('.overflow-auto').scrollTop`), 0)
    const visibleScroll = await evaluate(`(()=>{const pane=document.getElementById('services-runtime-status').closest('.overflow-auto');pane.scrollTop=pane.scrollHeight-pane.clientHeight;return pane.scrollTop})()`)
    await evaluate(`([...document.querySelectorAll('article')].find(node=>node.textContent.includes('MariaDB')).querySelector('button')).click()`)
    await waitFor(`document.getElementById('services-runtime-status').textContent.includes('running')`)
    await pause(400)
    assert.ok(Math.abs((await evaluate(`document.getElementById('services-runtime-status').closest('.overflow-auto').scrollTop`)) - visibleScroll) <= 1)
    console.log('PASS Settings requested state, top Runtime Status, rollback, startup radio, Services no-scroll and background no-scroll.')
    passed = true
  } catch (error) { console.error(error) }
  finally { clearTimeout(deadline); await runtime?.pauseBackgroundWork(); runtime?.dispose(); window?.destroy(); await (await import('../dist-electron/logs.js')).drainApplicationLogs(); await pause(200); if (passed) await rm(profile, { recursive: true, force: true, maxRetries: 20, retryDelay: 100 }).catch(error => console.error('Deferred fixture cleanup:', error)); else console.error('Retained Settings fixture:', profile); app.exit(passed ? 0 : 1) }
})
